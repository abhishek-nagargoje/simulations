-- =============================================================================
-- SAP ERP module: relational business data in PostgreSQL.
--
-- Data model
--   * Organization-wide reference data (no workspace): company codes, G/L
--     accounts, cost centers, materials, posting periods. Company code names are
--     configurable by teachers.
--   * Workspace data: every SAP ERP access session gets its own workspace,
--     cloned from the imported baseline when the session starts. Master data
--     that users may change (vendors, customers) and all operational documents
--     are workspace-scoped. Every key and foreign key includes workspace_id, so
--     one workspace can never reference or change another's rows.
--   * Preferences (variants, layouts, history) stay in the viewer's browser.
--
-- Security model (same as the platform schema)
--   * Schema erp is not exposed through the Data API; RLS is enabled on every
--     table with no policies; anon/authenticated have no privileges.
--   * Writes happen only through erp_commit_for_class (service_role), called by
--     the Next.js server after it has validated the student's session. The
--     workspace is derived from that session, never from the browser.
--   * erp_commit applies a batch atomically: number assignment, typed inserts and
--     updates, optimistic concurrency, status transitions, posting periods,
--     document balancing, clearing balance, GR/IR quantity reconciliation and
--     idempotency (a repeated request id returns the original result).
--
-- Forward-only, non-destructive. Re-runnable (IF NOT EXISTS / CREATE OR REPLACE).
-- =============================================================================

create schema if not exists erp;
revoke all on schema erp from public;
revoke all on schema erp from anon, authenticated;

-- -----------------------------------------------------------------------------
-- Helpers
-- -----------------------------------------------------------------------------

-- Fiscal year variant April-March (period 1 = April), as used by the module.
create or replace function erp.fiscal_year(d date)
returns integer language sql immutable set search_path = ''
as $$ select case when extract(month from d) >= 4 then extract(year from d)::int else extract(year from d)::int - 1 end $$;

create or replace function erp.fiscal_period(d date)
returns integer language sql immutable set search_path = ''
as $$ select case when extract(month from d) >= 4 then extract(month from d)::int - 3 else extract(month from d)::int + 9 end $$;

-- Raises a validation error whose detail is a safe, user-facing sentence.
create or replace function erp.fail(p_message text)
returns void language plpgsql set search_path = ''
as $$ begin raise exception 'erp_invalid' using errcode = 'P0001', detail = p_message; end $$;

create or replace function erp.conflict(p_message text)
returns void language plpgsql set search_path = ''
as $$ begin raise exception 'erp_conflict' using errcode = 'P0001', detail = p_message; end $$;

-- -----------------------------------------------------------------------------
-- Organization-wide reference data
-- -----------------------------------------------------------------------------
create table if not exists erp.company_codes (
  bukrs           text primary key check (bukrs ~ '^[0-9A-Z]{4}$'),
  butxt           text not null check (length(btrim(butxt)) between 1 and 80),
  ort01           text,
  land1           text,
  waers           text not null check (waers ~ '^[A-Z]{3}$'),
  ktopl           text,
  name_configured boolean not null default false,  -- set when a teacher renames it; imports then keep the name
  updated_at      timestamptz not null default now(),
  updated_by      uuid references auth.users (id) on delete set null,
  seq             bigint generated by default as identity
);

create table if not exists erp.gl_accounts (
  saknr  text primary key check (saknr ~ '^[0-9]{6,10}$'),
  txt50  text not null,
  ktoks  text,
  gltype text check (gltype in ('BS', 'PL')),
  xopvw  text check (xopvw = 'X'),
  recon  text,
  seq    bigint generated by default as identity
);

create table if not exists erp.cost_centers (
  kostl text primary key check (kostl ~ '^[0-9A-Z]{1,10}$'),
  ktext text not null,
  bukrs text not null references erp.company_codes (bukrs),
  verak text,
  prctr text,
  seq   bigint generated by default as identity
);

-- Services have no material number, so the description is the key (as in the module).
create table if not exists erp.materials (
  matnr text unique check (matnr ~ '^[0-9A-Z]{1,18}$'),
  maktx text primary key check (length(btrim(maktx)) between 1 and 60),
  meins text not null,
  matkl text,
  wgbez text,
  sakto text references erp.gl_accounts (saknr),
  price numeric(15,2) check (price >= 0),
  seq   bigint generated by default as identity
);

-- Open posting periods per company code and fiscal year (like transaction OB52).
create table if not exists erp.posting_periods (
  bukrs       text not null references erp.company_codes (bukrs),
  fiscal_year integer not null check (fiscal_year between 2000 and 2100),
  from_period integer not null check (from_period between 1 and 12),
  to_period   integer not null check (to_period between 1 and 12),
  updated_at  timestamptz not null default now(),
  updated_by  uuid references auth.users (id) on delete set null,
  primary key (bukrs, fiscal_year),
  check (from_period <= to_period)
);

-- -----------------------------------------------------------------------------
-- Workspaces
-- -----------------------------------------------------------------------------
create table if not exists erp.workspaces (
  id          uuid primary key default gen_random_uuid(),
  kind        text not null check (kind in ('baseline', 'session')),
  class_id    uuid unique references app.classes (id) on delete restrict,
  created_at  timestamptz not null default now(),
  reset_count integer not null default 0,
  last_reset_at timestamptz,
  check ((kind = 'baseline') = (class_id is null))
);
create unique index if not exists workspaces_one_baseline on erp.workspaces (kind) where kind = 'baseline';

