-- service_role: record a failed import attempt (the data change itself was rolled back).
create or replace function public.erp_record_import_failure(p_meta jsonb, p_error text)
returns void language sql security definer set search_path = ''
as $$
  insert into erp.import_runs (file_name, file_sha256, mapping_version, status, error, finished_at)
  values (left(coalesce(p_meta->>'file_name', 'unknown'), 200), coalesce(p_meta->>'file_sha256', repeat('0', 64)),
          coalesce(p_meta->>'mapping_version', 'unknown'), 'failed', left(p_error, 2000), now());
$$;

-- Student access (service_role, called after the server validated the session):
-- the workspace is derived from the access session, which must be open.
create or replace function erp.session_workspace(p_class_id uuid)
returns uuid language plpgsql stable set search_path = ''
as $$
declare v uuid;
begin
  select w.id into v
    from app.classes c
    join erp.workspaces w on w.class_id = c.id
   where c.id = p_class_id and c.status = 'active' and c.expires_at > now();
  if v is null then raise exception 'not_authorized' using errcode = '42501'; end if;
  return v;
end $$;

create or replace function public.erp_export_for_class(p_class_id uuid)
returns jsonb language sql stable security definer set search_path = ''
as $$ select erp.export(erp.session_workspace(p_class_id)) $$;

create or replace function public.erp_commit_for_class(p_class_id uuid, p_request_id uuid, p_ops jsonb, p_actor text)
returns jsonb language sql security definer set search_path = ''
as $$ select erp.commit(erp.session_workspace(p_class_id), p_request_id, p_ops, p_actor) $$;

-- Teacher: configuration overview.
create or replace function public.admin_erp_overview()
returns jsonb language plpgsql stable security definer set search_path = ''
as $$
declare v_base uuid;
begin
  perform app.require_admin();
  v_base := erp.baseline_id();
  return jsonb_build_object(
    'baseline_loaded', v_base is not null and exists (select 1 from erp.vendors where workspace_id = v_base),
    'last_import', (select to_jsonb(i) - 'counts' from (
                      select id, file_name, status, mapping_version, started_at, finished_at, error
                        from erp.import_runs order by id desc limit 1) i),
    'company_codes', coalesce((select jsonb_agg(jsonb_build_object('bukrs', c.bukrs, 'name', c.butxt, 'city', c.ort01,
                                                  'currency', c.waers, 'configured', c.name_configured) order by c.bukrs)
                                 from erp.company_codes c), '[]'::jsonb),
    'posting_periods', coalesce((select jsonb_agg(jsonb_build_object('bukrs', p.bukrs, 'fiscal_year', p.fiscal_year,
                                                    'from_period', p.from_period, 'to_period', p.to_period)
                                                  order by p.bukrs, p.fiscal_year)
                                   from erp.posting_periods p), '[]'::jsonb));
end $$;

create or replace function public.admin_update_company_code(p_bukrs text, p_name text)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := app.require_admin();
  v_name text := btrim(coalesce(p_name, ''));
begin
  if length(v_name) < 2 or length(v_name) > 80 then
    raise exception 'invalid_name' using errcode = '22023';
  end if;
  update erp.company_codes set butxt = v_name, name_configured = true, updated_at = now(), updated_by = v_uid
   where bukrs = p_bukrs;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  insert into app.audit_log (actor_id, action, details)
  values (v_uid, 'erp.company_code_renamed', jsonb_build_object('bukrs', p_bukrs, 'name', v_name));
end $$;

create or replace function public.admin_set_posting_period(p_bukrs text, p_fiscal_year integer, p_from integer, p_to integer)
returns void language plpgsql security definer set search_path = ''
as $$
declare v_uid uuid := app.require_admin();
begin
  if p_fiscal_year is null or p_fiscal_year not between 2000 and 2100
     or p_from is null or p_to is null or p_from not between 1 and 12 or p_to not between 1 and 12 or p_from > p_to then
    raise exception 'invalid_request' using errcode = '22023';
  end if;
  if not exists (select 1 from erp.company_codes where bukrs = p_bukrs) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  insert into erp.posting_periods (bukrs, fiscal_year, from_period, to_period, updated_at, updated_by)
  values (p_bukrs, p_fiscal_year, p_from, p_to, now(), v_uid)
  on conflict (bukrs, fiscal_year) do update
    set from_period = excluded.from_period, to_period = excluded.to_period, updated_at = now(), updated_by = v_uid;
  insert into app.audit_log (actor_id, action, details)
  values (v_uid, 'erp.posting_period_set', jsonb_build_object('bukrs', p_bukrs, 'fiscal_year', p_fiscal_year,
                                                             'from_period', p_from, 'to_period', p_to));
end $$;

-- Teacher: restore an active session's workspace to the imported baseline.
create or replace function public.admin_reset_workspace(p_class_id uuid)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := app.require_admin();
  v_cls app.classes;
  v_ws uuid;
begin
  select * into v_cls from app.classes where id = p_class_id for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  if v_cls.status <> 'active' or v_cls.expires_at <= now() then
    raise exception 'invalid_state' using errcode = '55000';
  end if;
  select id into v_ws from erp.workspaces where class_id = p_class_id for update;
  if v_ws is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  perform erp.delete_workspace_data(v_ws);
  perform erp.copy_workspace(erp.baseline_id(), v_ws);
  perform erp.number_init(v_ws);
  update erp.workspaces set reset_count = reset_count + 1, last_reset_at = now() where id = v_ws;
  set constraints all immediate;
  insert into app.audit_log (actor_id, action, class_id, details)
  values (v_uid, 'erp.workspace_reset', p_class_id, '{}'::jsonb);
end $$;

