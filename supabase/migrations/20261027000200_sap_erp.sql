-- Same value, comparing numbers numerically and treating '' like null.
create or replace function erp.same(a jsonb, b jsonb)
returns boolean language plpgsql immutable set search_path = ''
as $$
declare ta text := nullif(a #>> '{}', ''); tb text := nullif(b #>> '{}', '');
begin
  if ta is null or tb is null then return ta is null and tb is null; end if;
  if ta ~ '^-?[0-9]+(\.[0-9]+)?$' and tb ~ '^-?[0-9]+(\.[0-9]+)?$' then return ta::numeric = tb::numeric; end if;
  return ta = tb;
end $$;

-- Validates and lower-cases a row object coming from the module.
-- Inserts drop empty values (they become NULL); updates keep them as explicit nulls.
create or replace function erp.normalize(p_code text, p_obj jsonb, p_insert boolean)
returns jsonb language plpgsql stable set search_path = ''
as $$
declare
  v_out jsonb := '{}';
  r record;
  m erp.table_columns;
  v_txt text;
begin
  if p_obj is null or jsonb_typeof(p_obj) <> 'object' then perform erp.fail('Invalid request.'); end if;
  for r in select key, value from jsonb_each(p_obj) loop
    select * into m from erp.table_columns c where c.code = p_code and c.col = lower(r.key);
    if not found then
      if r.value in ('""'::jsonb, 'null'::jsonb) then continue; end if;
      perform erp.fail(format('Field %s is not part of this record.', r.key));
    end if;
    if r.value in ('""'::jsonb, 'null'::jsonb) then
      if not p_insert then v_out := v_out || jsonb_build_object(m.col, null); end if;
      continue;
    end if;
    v_txt := r.value #>> '{}';
    if jsonb_typeof(r.value) in ('object', 'array') then
      perform erp.fail(format('Field %s has an invalid value.', m.label));
    elsif m.kind in ('num', 'int') then
      if v_txt !~ '^-?[0-9]{1,13}(\.[0-9]+)?$' or (m.kind = 'int' and v_txt !~ '^-?[0-9]{1,9}$') then
        perform erp.fail(format('Field %s must be a number.', m.label));
      end if;
      v_out := v_out || jsonb_build_object(m.col, v_txt::numeric);
    elsif m.kind = 'date' then
      if v_txt !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
        perform erp.fail(format('Field %s must be a valid date.', m.label));
      end if;
      begin
        perform v_txt::date;
      exception when others then
        perform erp.fail(format('Field %s must be a valid date.', m.label));
      end;
      v_out := v_out || jsonb_build_object(m.col, v_txt);
    else
      if length(v_txt) > 300 then perform erp.fail(format('Field %s is too long.', m.label)); end if;
      v_out := v_out || jsonb_build_object(m.col, v_txt);
    end if;
  end loop;
  return v_out;
end $$;

create or replace function erp.key_where(p_keys text[], p_alias text)
returns text language sql immutable set search_path = ''
as $$ select string_agg(format('%I.%I = ($2->>%L)', p_alias, k, k), ' and ') from unnest(p_keys) k $$;

create or replace function erp.get_row(p_ws uuid, p_reg erp.table_registry, p_key jsonb, p_lock boolean)
returns jsonb language plpgsql set search_path = ''
as $$
declare v jsonb;
begin
  -- The alias must not collide with a column name (upload_logs has a column "t").
  execute format('select to_jsonb(row_) - ''workspace_id'' - ''seq'' from erp.%I row_ where row_.workspace_id = $1 and %s %s',
                 p_reg.relname, erp.key_where(p_reg.key_cols, 'row_'), case when p_lock then 'for update' else '' end)
    into v using p_ws, p_key;
  return v;
end $$;

create or replace function erp.next_number(p_ws uuid, p_name text)
returns text language plpgsql set search_path = ''
as $$
declare
  d erp.number_range_defs;
  v bigint;
begin
  select * into d from erp.number_range_defs where name = p_name;
  if not found then perform erp.fail('Unknown number range.'); end if;
  update erp.number_ranges set next_value = next_value + 1
   where workspace_id = p_ws and name = p_name
  returning next_value - 1 into v;
  if v is null then
    perform erp.number_init(p_ws);
    update erp.number_ranges set next_value = next_value + 1
     where workspace_id = p_ws and name = p_name
    returning next_value - 1 into v;
  end if;
  return d.prefix || case when d.pad > 0 then lpad(v::text, d.pad, '0') else v::text end;
end $$;

-- Starts every number range after the highest number already present.
create or replace function erp.number_init(p_ws uuid)
returns void language plpgsql set search_path = ''
as $$
declare
  d erp.number_range_defs;
  c text;
  v_rel text;
  v_max numeric;
  v numeric;
begin
  for d in select * from erp.number_range_defs loop
    select relname into v_rel from erp.table_registry where code = d.code;
    v_max := 0;
    foreach c in array d.cols loop
      execute format($q$select coalesce(max(nullif(regexp_replace(t.%I, '\D', '', 'g'), '')::numeric), 0)
                        from erp.%I t where t.workspace_id = $1$q$, c, v_rel)
        into v using p_ws;
      v_max := greatest(v_max, v);
    end loop;
    insert into erp.number_ranges (workspace_id, name, next_value)
    values (p_ws, d.name, greatest(v_max + 1, d.min_value)::bigint)
    on conflict (workspace_id, name) do update
      set next_value = greatest(erp.number_ranges.next_value, excluded.next_value);
  end loop;
end $$;

-- Copies all workspace data from one workspace into another (same order).
create or replace function erp.copy_workspace(p_src uuid, p_dst uuid)
returns void language plpgsql set search_path = ''
as $$
declare
  r erp.table_registry;
  v_cols text;
begin
  for r in select * from erp.table_registry where scope = 'workspace' order by ord loop
    select string_agg(format('%I', c), ', ' order by o) into v_cols from unnest(erp.cols(r.code)) with ordinality as x(c, o);
    execute format('insert into erp.%I (workspace_id, %s) select $2, %s from erp.%I where workspace_id = $1 order by seq',
                   r.relname, v_cols, v_cols, r.relname)
      using p_src, p_dst;
  end loop;
  insert into erp.document_lines (workspace_id, doc_table, belnr, buzei, bschl, koart, acc, amt, mwskz, zuonr, sgtxt, kostl, umskz, gsber)
  select p_dst, doc_table, belnr, buzei, bschl, koart, acc, amt, mwskz, zuonr, sgtxt, kostl, umskz, gsber
    from erp.document_lines where workspace_id = p_src;
end $$;

create or replace function erp.delete_workspace_data(p_ws uuid)
returns void language plpgsql set search_path = ''
as $$
declare r erp.table_registry;
begin
  set constraints all deferred;
  delete from erp.document_lines where workspace_id = p_ws;
  delete from erp.number_ranges where workspace_id = p_ws;
  for r in select * from erp.table_registry where scope = 'workspace' order by ord desc loop
    execute format('delete from erp.%I where workspace_id = $1', r.relname) using p_ws;
  end loop;
end $$;

create or replace function erp.baseline_id()
returns uuid language sql stable set search_path = ''
as $$ select id from erp.workspaces where kind = 'baseline' $$;

create or replace function erp.create_workspace(p_class_id uuid)
returns uuid language plpgsql set search_path = ''
as $$
declare
  v_base uuid := erp.baseline_id();
  v_id uuid;
begin
  select id into v_id from erp.workspaces where class_id = p_class_id;
  if found then return v_id; end if;
  if v_base is null or not exists (select 1 from erp.vendors where workspace_id = v_base) then
    raise exception 'erp_baseline_missing' using errcode = '55000';
  end if;
  insert into erp.workspaces (kind, class_id) values ('session', p_class_id) returning id into v_id;
  perform erp.copy_workspace(v_base, v_id);
  perform erp.number_init(v_id);
  return v_id;
end $$;

-- An SAP ERP access session gets its workspace when it starts.
create or replace function app.after_class_start(p_class_id uuid)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if exists (select 1 from app.classes c join app.simulations s on s.id = c.simulation_id
              where c.id = p_class_id and s.slug = 'sap-erp') then
    perform erp.create_workspace(p_class_id);
  end if;
end $$;

-- Posting date must fall in the document's fiscal year and an open period.
create or replace function erp.assert_posting(p_bukrs text, p_budat date, p_gjahr text, p_what text)
returns void language plpgsql stable set search_path = ''
as $$
declare
  v_fy integer := erp.fiscal_year(p_budat);
  v_per integer := erp.fiscal_period(p_budat);
begin
  if p_gjahr is not null and p_gjahr <> v_fy::text then
    perform erp.fail(format('%s: posting date %s belongs to fiscal year %s, not %s.',
                            p_what, to_char(p_budat, 'DD.MM.YYYY'), v_fy, p_gjahr));
  end if;
  if not exists (select 1 from erp.posting_periods p
                  where p.bukrs = p_bukrs and p.fiscal_year = v_fy and v_per between p.from_period and p.to_period) then
    perform erp.fail(format('Posting period %s/%s is not open for company code %s.', lpad(v_per::text, 3, '0'), v_fy, p_bukrs));
  end if;
end $$;

-- Debit posting keys (positive amounts); all others are credit keys.
create or replace function erp.is_debit_key(p_bschl text)
returns boolean language sql immutable set search_path = ''
as $$ select p_bschl in ('01','02','03','04','05','06','07','08','09','21','22','24','25','29','40','70','86','89') $$;

-- Writes the explicit line items of a new document and validates them.
create or replace function erp.put_lines(p_ws uuid, p_code text, p_belnr text, p_lines jsonb)
returns void language plpgsql set search_path = ''
as $$
declare
  l jsonb;
  i integer := 0;
  v_amt numeric;
  v_buzei text;
begin
  if jsonb_typeof(p_lines) <> 'array' then perform erp.fail('Invalid line items.'); end if;
  for l in select value from jsonb_array_elements(p_lines) loop
    i := i + 1;
    if jsonb_typeof(l) <> 'object' then perform erp.fail('Invalid line items.'); end if;
    if coalesce(l->>'AMT', '') !~ '^-?[0-9]{1,13}(\.[0-9]+)?$' then
      perform erp.fail(format('Document %s line %s: the amount is invalid.', p_belnr, i));
    end if;
    v_amt := (l->>'AMT')::numeric;
    if v_amt = 0 then perform erp.fail(format('Document %s line %s: enter an amount.', p_belnr, i)); end if;
    v_buzei := coalesce(nullif(l->>'BUZEI', ''), lpad(i::text, 3, '0'));
    if coalesce(l->>'BSCHL', '') !~ '^[0-9]{2}$' then
      perform erp.fail(format('Document %s line %s: the posting key is invalid.', p_belnr, i));
    end if;
    if erp.is_debit_key(l->>'BSCHL') <> (v_amt > 0) then
      perform erp.fail(format('Document %s line %s: amount sign does not match posting key %s.', p_belnr, i, l->>'BSCHL'));
    end if;
    case l->>'KOART'
      when 'S' then
        if not exists (select 1 from erp.gl_accounts g where g.saknr = l->>'ACC') then
          perform erp.fail(format('Document %s line %s: G/L account %s does not exist.', p_belnr, i, l->>'ACC'));
        end if;
      when 'K' then
        if not exists (select 1 from erp.vendors v where v.workspace_id = p_ws and v.lifnr = l->>'ACC') then
          perform erp.fail(format('Document %s line %s: vendor %s does not exist.', p_belnr, i, l->>'ACC'));
        end if;
      when 'D' then
        if not exists (select 1 from erp.customers c where c.workspace_id = p_ws and c.kunnr = l->>'ACC') then
          perform erp.fail(format('Document %s line %s: customer %s does not exist.', p_belnr, i, l->>'ACC'));
        end if;
      else
        perform erp.fail(format('Document %s line %s: the account type is invalid.', p_belnr, i));
    end case;
    if nullif(l->>'KOSTL', '') is not null and not exists (select 1 from erp.cost_centers k where k.kostl = l->>'KOSTL') then
      perform erp.fail(format('Document %s line %s: cost center %s does not exist.', p_belnr, i, l->>'KOSTL'));
    end if;
    insert into erp.document_lines (workspace_id, doc_table, belnr, buzei, bschl, koart, acc, amt,
                                    mwskz, zuonr, sgtxt, kostl, umskz, gsber)
    values (p_ws, p_code, p_belnr, v_buzei, l->>'BSCHL', l->>'KOART', l->>'ACC', v_amt,
            nullif(l->>'MWSKZ', ''), nullif(l->>'ZUONR', ''), nullif(l->>'SGTXT', ''), nullif(l->>'KOSTL', ''),
            nullif(l->>'UMSKZ', ''), nullif(l->>'GSBER', ''));
  end loop;
end $$;

-- Changing a posted document's lines: only assignment and text may change.
create or replace function erp.update_lines(p_ws uuid, p_code text, p_belnr text, p_lines jsonb)
returns void language plpgsql set search_path = ''
as $$
declare
  l jsonb;
  d erp.document_lines;
  n integer := 0;
begin
  if jsonb_typeof(p_lines) <> 'array' then perform erp.fail('Invalid line items.'); end if;
  for l in select value from jsonb_array_elements(p_lines) loop
    n := n + 1;
    select * into d from erp.document_lines
     where workspace_id = p_ws and doc_table = p_code and belnr = p_belnr and buzei = l->>'BUZEI' for update;
    if not found or d.bschl is distinct from l->>'BSCHL' or d.acc is distinct from l->>'ACC'
       or not erp.same(to_jsonb(d.amt), l->'AMT') or d.koart is distinct from l->>'KOART'
       or coalesce(d.kostl, '') <> coalesce(l->>'KOSTL', '') or coalesce(d.mwskz, '') <> coalesce(l->>'MWSKZ', '') then
      perform erp.fail(format('Document %s: only assignment and text of a posted line item can be changed.', p_belnr));
    end if;
    update erp.document_lines set zuonr = nullif(l->>'ZUONR', ''), sgtxt = nullif(l->>'SGTXT', '')
     where workspace_id = p_ws and doc_table = p_code and belnr = p_belnr and buzei = d.buzei;
  end loop;
  if n <> (select count(*) from erp.document_lines where workspace_id = p_ws and doc_table = p_code and belnr = p_belnr) then
    perform erp.fail(format('Document %s: line items cannot be added or removed after posting.', p_belnr));
  end if;
end $$;

-- Applies one insert or update. Every change is recorded in pg_temp.erp_chg.
create or replace function erp.apply_op(p_ws uuid, p_op jsonb, p_seq integer)
returns void language plpgsql set search_path = ''
as $$
declare
  v_code text := p_op->>'t';
  v_kind text := p_op->>'op';
  g erp.table_registry;
  v_row jsonb; v_lines jsonb; v_norm jsonb; v_key jsonb := '{}'; v_old jsonb; v_new jsonb;
  v_allowed text[];
  v_cols text; v_sel text; v_set text;
  r record;
  c text;
begin
  select * into g from erp.table_registry where code = v_code;
  if not found or g.scope <> 'workspace' then
    perform erp.fail(format('Records of type %s cannot be changed.', coalesce(v_code, '?')));
  end if;

  if v_kind = 'insert' then
    if not g.insertable then perform erp.fail(format('%s cannot be created here.', g.description)); end if;
    v_row := p_op->'row';
    if v_row is null or jsonb_typeof(v_row) <> 'object' then perform erp.fail('Invalid request.'); end if;
    v_lines := v_row->'IT';
    v_norm := erp.normalize(v_code, v_row - 'IT', true);
    foreach c in array g.key_cols loop
      if coalesce(v_norm->>c, '') = '' then perform erp.fail(format('%s: key field %s is missing.', g.description, upper(c))); end if;
      v_key := v_key || jsonb_build_object(c, v_norm->>c);
    end loop;
    select string_agg(format('%I', k), ', '), string_agg(format('r.%I', k), ', ')
      into v_cols, v_sel from jsonb_object_keys(v_norm) k;
    begin
      execute format('insert into erp.%I (workspace_id, %s) select $1, %s from jsonb_populate_record(null::erp.%I, $2) r',
                     g.relname, v_cols, v_sel, g.relname)
        using p_ws, v_norm;
    exception when unique_violation then
      perform erp.conflict(format('%s already exists.', erp.describe(v_code, v_norm)));
    end;
    v_new := erp.get_row(p_ws, g, v_key, false);
    insert into pg_temp.erp_chg values (p_seq, v_code, 'insert', null, v_new);
    if v_lines is not null and v_lines <> 'null'::jsonb then
      if v_code not in ('BSIK', 'BSID', 'GLDOC') then perform erp.fail('Invalid request.'); end if;
      perform erp.put_lines(p_ws, v_code, v_norm->>'belnr', v_lines);
    end if;

  elsif v_kind = 'update' then
    if p_op->'key' is null or jsonb_typeof(p_op->'key') <> 'object' then perform erp.fail('Invalid request.'); end if;
    foreach c in array g.key_cols loop
      if coalesce(p_op->'key'->>upper(c), '') = '' then perform erp.fail('Invalid request.'); end if;
      v_key := v_key || jsonb_build_object(c, p_op->'key'->>upper(c));
    end loop;
    v_old := erp.get_row(p_ws, g, v_key, true);
    if v_old is null then
      perform erp.conflict(format('%s no longer exists. Reload the data and try again.', erp.describe(v_code, v_key)));
    end if;
    -- Optimistic concurrency: the browser states the values it based the change on.
    if p_op ? 'expect' then
      for r in select key, value from jsonb_each(p_op->'expect') loop
        if lower(r.key) <> 'it' and not erp.same(v_old->lower(r.key), r.value) then
          perform erp.conflict(format('%s was changed by another user. The data has been reloaded; repeat the step.',
                                      erp.describe(v_code, v_old)));
        end if;
      end loop;
    end if;
    v_lines := p_op->'set'->'IT';
    v_norm := erp.normalize(v_code, coalesce(p_op->'set', '{}'::jsonb) - 'IT', false);
    v_allowed := g.updatable_cols;
    if v_code = 'RBKP' and v_old->>'status' = 'Parked' then
      -- A parked invoice may be edited completely until it is posted.
      v_allowed := array(select col from unnest(erp.cols('RBKP')) col where col <> all (g.key_cols));
    end if;
    for r in select key from jsonb_object_keys(v_norm) key loop
      if erp.same(v_old->r.key, v_norm->r.key) then
        v_norm := v_norm - r.key;  -- unchanged: nothing to write
      elsif not (r.key = any (v_allowed)) then
        perform erp.fail(format('%s: field %s cannot be changed.', erp.describe(v_code, v_old),
                                (select label from erp.table_columns where code = v_code and col = r.key)));
      end if;
    end loop;
    if v_norm <> '{}'::jsonb then
      select string_agg(format('%I = src_.%I', k, k), ', ') into v_set from jsonb_object_keys(v_norm) k;
      execute format('update erp.%I tgt_ set %s from jsonb_populate_record(null::erp.%I, $3) src_ where tgt_.workspace_id = $1 and %s',
                     g.relname, v_set, g.relname, erp.key_where(g.key_cols, 'tgt_'))
        using p_ws, v_key, v_norm;
    end if;
    v_new := erp.get_row(p_ws, g, v_key, false);
    insert into pg_temp.erp_chg values (p_seq, v_code, 'update', v_old, v_new);
    if v_lines is not null and v_lines <> 'null'::jsonb then
      if v_code not in ('BSIK', 'BSID', 'GLDOC') then perform erp.fail('Invalid request.'); end if;
      perform erp.update_lines(p_ws, v_code, v_old->>'belnr', v_lines);
    end if;
  else
    perform erp.fail('Invalid request.');
  end if;
end $$;

-- Business rules that span several records of one batch.
create or replace function erp.validate_batch(p_ws uuid)
returns void language plpgsql set search_path = ''
as $$
declare
  r record;
  v_n integer;
  v_sum numeric;
  v_amt numeric;
  v_x text;
begin
  -- 1. Status transitions
  for r in
    select c.code, c.old, c.new, s.col
      from pg_temp.erp_chg c
      join erp.table_registry g on g.code = c.code
      cross join unnest(g.status_cols) s(col)
     where c.op = 'update' and (c.old->>s.col) is distinct from (c.new->>s.col)
  loop
    if not exists (select 1 from erp.status_transitions t
                    where t.code = r.code and t.col = r.col and t.from_val = r.old->>r.col and t.to_val = r.new->>r.col) then
      perform erp.fail(format('%s: status cannot change from "%s" to "%s".',
                              erp.describe(r.code, r.new), r.old->>r.col, r.new->>r.col));
    end if;
  end loop;

  -- 2. New accounting documents
  for r in select c.code, c.new from pg_temp.erp_chg c where c.op = 'insert' and c.code in ('BSIK', 'BSID', 'GLDOC') loop
    perform erp.assert_posting(r.new->>'bukrs', (r.new->>'budat')::date, r.new->>'gjahr', 'Document ' || (r.new->>'belnr'));
    select (select count(*) from erp.vendor_items where workspace_id = p_ws and belnr = r.new->>'belnr')
         + (select count(*) from erp.customer_items where workspace_id = p_ws and belnr = r.new->>'belnr')
         + (select count(*) from erp.gl_documents where workspace_id = p_ws and belnr = r.new->>'belnr') into v_n;
    if v_n > 1 then perform erp.conflict(format('Document number %s is already in use.', r.new->>'belnr')); end if;
    select count(*), coalesce(sum(amt), 0) into v_n, v_sum
      from erp.document_lines where workspace_id = p_ws and doc_table = r.code and belnr = r.new->>'belnr';
    if v_n > 0 then
      if v_n < 2 then perform erp.fail(format('Document %s needs at least two line items.', r.new->>'belnr')); end if;
      if v_sum <> 0 then
        perform erp.fail(format('Document %s is not balanced: debit and credit differ by %s.', r.new->>'belnr', to_char(v_sum, 'FM999G999G999G990D00')));
      end if;
      if r.code <> 'GLDOC' and not exists (
           select 1 from erp.document_lines l where l.workspace_id = p_ws and l.doc_table = r.code and l.belnr = r.new->>'belnr'
              and l.koart = case r.code when 'BSIK' then 'K' else 'D' end
              and l.acc = coalesce(r.new->>'lifnr', r.new->>'kunnr') and abs(l.amt) = (r.new->>'wrbtr')::numeric) then
        perform erp.fail(format('Document %s: the partner line does not match the document header.', r.new->>'belnr'));
      end if;
    elsif r.code = 'GLDOC' and r.new->>'blart' not in ('KZ', 'AB') then
      perform erp.fail(format('Document %s has no line items.', r.new->>'belnr'));
    elsif r.code <> 'GLDOC' and r.new->>'blart' in ('KR', 'KG', 'DR', 'DG') and r.new->>'hkont' is null then
      perform erp.fail(format('Document %s: enter the offsetting G/L account.', r.new->>'belnr'));
    end if;
    -- Duplicate invoice check (same vendor, company code and reference).
    if r.code = 'BSIK' and r.new->>'blart' = 'KR' and r.new->>'xblnr' is not null then
      select v.belnr into v_x from erp.vendor_items v
       where v.workspace_id = p_ws and v.lifnr = r.new->>'lifnr' and v.bukrs = r.new->>'bukrs'
         and upper(v.xblnr) = upper(r.new->>'xblnr') and v.blart = 'KR' and v.status <> 'Reversed'
         and v.belnr <> r.new->>'belnr'
       limit 1;
      if v_x is not null then
        perform erp.fail(format('Duplicate invoice: reference %s of vendor %s is already posted in document %s.',
                                r.new->>'xblnr', r.new->>'lifnr', v_x));
      end if;
    end if;
  end loop;

  -- 3. Reversals point to a reversal document posted in the same batch.
  for r in select c.code, c.new from pg_temp.erp_chg c
            where c.op = 'update' and c.code in ('BSIK', 'BSID', 'GLDOC')
              and c.new->>'status' = 'Reversed' and c.old->>'status' <> 'Reversed' loop
    if not exists (select 1 from pg_temp.erp_chg x where x.op = 'insert' and x.code = 'GLDOC'
                    and x.new->>'belnr' = r.new->>'stblg') then
      perform erp.fail(format('Document %s: the reversal document is missing.', r.new->>'belnr'));
    end if;
  end loop;

  -- 4. Down payment amounts may only be reduced by a transfer posting.
  for r in select c.old, c.new from pg_temp.erp_chg c
            where c.op = 'update' and c.code = 'BSIK' and (c.old->>'wrbtr')::numeric <> (c.new->>'wrbtr')::numeric loop
    if r.old->>'umskz' is distinct from 'A' or (r.new->>'wrbtr')::numeric >= (r.old->>'wrbtr')::numeric then
      perform erp.fail(format('Document %s: the amount of a posted document cannot be changed.', r.new->>'belnr'));
    end if;
  end loop;

  -- 5. Open-item clearing must balance (cleared items - residual items - difference postings = 0).
  if exists (select 1 from pg_temp.erp_chg c where c.code in ('BSIK', 'BSID') and c.new->>'status' = 'Cleared'
              and (c.op = 'insert' or c.old->>'status' <> 'Cleared')) then
    for v_x in select distinct c.new->>'augbl' from pg_temp.erp_chg c
                where c.code in ('BSIK', 'BSID') and c.new->>'status' = 'Cleared' and (c.op = 'insert' or c.old->>'status' <> 'Cleared') loop
      if not exists (select 1 from erp.vendor_items where workspace_id = p_ws and belnr = v_x)
         and not exists (select 1 from erp.customer_items where workspace_id = p_ws and belnr = v_x)
         and not exists (select 1 from erp.gl_documents where workspace_id = p_ws and belnr = v_x) then
        perform erp.fail(format('Clearing document %s does not exist.', v_x));
      end if;
    end loop;
    select coalesce(sum(case when c.new->>'shkzg' = 'S' then 1 else -1 end * (c.new->>'wrbtr')::numeric), 0) into v_sum
      from pg_temp.erp_chg c
     where c.code in ('BSIK', 'BSID') and c.new->>'status' = 'Cleared' and (c.op = 'insert' or c.old->>'status' <> 'Cleared')
       and coalesce(c.new->>'umskz', '') <> 'A';
    select v_sum - coalesce(sum(case when c.new->>'shkzg' = 'S' then 1 else -1 end * (c.new->>'wrbtr')::numeric), 0) into v_sum
      from pg_temp.erp_chg c
     where c.code in ('BSIK', 'BSID') and c.op = 'insert' and c.new->>'status' = 'Open' and c.new->>'sgtxt' like 'Residual item%';
    select v_sum - coalesce(sum(l.amt), 0) into v_sum
      from erp.document_lines l
     where l.workspace_id = p_ws and l.doc_table = 'GLDOC'
       and l.belnr in (select c.new->>'belnr' from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'GLDOC')
       and l.belnr in (select c.new->>'augbl' from pg_temp.erp_chg c where c.code in ('BSIK', 'BSID') and c.new->>'status' = 'Cleared');
    if abs(v_sum) > 0.009 then
      perform erp.fail(format('The clearing is not balanced: difference %s. Assign the difference or create a residual item.',
                              to_char(v_sum, 'FM999G999G999G990D00')));
    end if;
  end if;
  -- Resetting a clearing must reset all of its items.
  for v_x in select distinct c.old->>'augbl' from pg_temp.erp_chg c
              where c.op = 'update' and c.code in ('BSIK', 'BSID') and c.old->>'status' = 'Cleared' and c.new->>'status' <> 'Cleared' loop
    if exists (select 1 from erp.vendor_items where workspace_id = p_ws and augbl = v_x and status = 'Cleared')
       or exists (select 1 from erp.customer_items where workspace_id = p_ws and augbl = v_x and status = 'Cleared') then
      perform erp.fail(format('Clearing %s must be reset for all of its items.', v_x));
    end if;
  end loop;

  -- 6. Purchase orders: new items start without receipts or invoices; quantity
  --    and price are frozen once goods have been received.
  for r in select c.new from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'EKPO' loop
    if (r.new->>'wemng')::numeric <> 0 or (r.new->>'remng')::numeric <> 0 or r.new->>'status' <> 'Not delivered' then
      perform erp.fail(format('%s: a new item cannot have receipts or invoices.', erp.describe('EKPO', r.new)));
    end if;
  end loop;
  for r in select c.old, c.new from pg_temp.erp_chg c where c.op = 'update' and c.code = 'EKPO'
            and ((c.old->>'menge')::numeric <> (c.new->>'menge')::numeric or (c.old->>'netpr')::numeric <> (c.new->>'netpr')::numeric) loop
    if (r.old->>'wemng')::numeric > 0 then
      perform erp.fail(format('%s: quantity and price cannot be changed after a goods receipt.', erp.describe('EKPO', r.new)));
    end if;
  end loop;

  -- 7. Goods receipts: the PO's received quantity changes exactly by the material document.
  for r in
    with gr as (
      select c.new->>'ebeln' as e, c.new->>'ebelp' as p,
             sum(case when c.new->>'bwart' = '101' then 1 else -1 end * (c.new->>'menge')::numeric) as q
        from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'MSEG' group by 1, 2),
    po as (
      select c.new->>'ebeln' as e, c.new->>'ebelp' as p,
             sum((c.new->>'wemng')::numeric - (c.old->>'wemng')::numeric) as d
        from pg_temp.erp_chg c where c.op = 'update' and c.code = 'EKPO' group by 1, 2)
    select coalesce(gr.e, po.e) as e, coalesce(gr.p, po.p) as p
      from gr full join po on gr.e = po.e and gr.p = po.p
     where coalesce(gr.q, 0) <> coalesce(po.d, 0)
  loop
    perform erp.fail(format('Purchase order %s item %s: the received quantity does not match the material document.', r.e, r.p));
  end loop;
  for r in select c.new from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'MSEG' loop
    perform erp.assert_posting(
      (select p.bukrs from erp.po_items p where p.workspace_id = p_ws and p.ebeln = r.new->>'ebeln' and p.ebelp = r.new->>'ebelp'),
      (r.new->>'budat')::date, null, 'Material document ' || (r.new->>'mblnr'));
  end loop;

  -- 8. Invoices: newly posted invoices are in an open period, not duplicates, and
  --    change the PO's invoiced quantity by their quantity; cancellations reduce it.
  for r in select c.new from pg_temp.erp_chg c
            where c.code = 'RBKP' and c.new->>'status' = 'Posted' and (c.op = 'insert' or c.old->>'status' <> 'Posted') loop
    perform erp.assert_posting(r.new->>'bukrs', (r.new->>'budat')::date, r.new->>'gjahr', 'Invoice document ' || (r.new->>'belnr'));
    if r.new->>'xblnr' is not null then
      select i.belnr into v_x from erp.invoice_items i
       where i.workspace_id = p_ws and i.lifnr = r.new->>'lifnr' and upper(i.xblnr) = upper(r.new->>'xblnr')
         and i.status = 'Posted' and i.belnr <> r.new->>'belnr' and i.type = r.new->>'type'
       limit 1;
      if v_x is not null then
        perform erp.fail(format('Duplicate invoice: reference %s of vendor %s is already posted in invoice document %s.',
                                r.new->>'xblnr', r.new->>'lifnr', v_x));
      end if;
    end if;
  end loop;
  for r in
    with ir as (
      select c.new->>'ebeln' as e, c.new->>'ebelp' as p,
             sum(case when c.new->>'status' = 'Posted' and (c.op = 'insert' or c.old->>'status' = 'Parked')
                        then case when c.new->>'type' = 'Credit memo' then -1 else 1 end * (c.new->>'menge')::numeric
                      when c.new->>'status' = 'Cancelled' and c.old->>'status' = 'Posted' and c.new->>'type' <> 'Credit memo'
                        then -(c.new->>'menge')::numeric
                      else 0 end) as lo,
             sum(case when c.new->>'status' = 'Posted' and (c.op = 'insert' or c.old->>'status' = 'Parked')
                        then case when c.new->>'type' = 'Credit memo' then -1 else 1 end * (c.new->>'menge')::numeric
                      when c.new->>'status' = 'Cancelled' and c.old->>'status' = 'Posted' and c.new->>'type' = 'Credit memo'
                        then (c.new->>'menge')::numeric
                      else 0 end) as hi
        from pg_temp.erp_chg c where c.code = 'RBKP' group by 1, 2),
    po as (
      select c.new->>'ebeln' as e, c.new->>'ebelp' as p,
             sum((c.new->>'remng')::numeric - (c.old->>'remng')::numeric) as d
        from pg_temp.erp_chg c where c.op = 'update' and c.code = 'EKPO' group by 1, 2)
    select coalesce(ir.e, po.e) as e, coalesce(ir.p, po.p) as p
      from ir full join po on ir.e = po.e and ir.p = po.p
     where coalesce(po.d, 0) < coalesce(ir.lo, 0) - 0.0005 or coalesce(po.d, 0) > coalesce(ir.hi, 0) + 0.0005
  loop
    perform erp.fail(format('Purchase order %s item %s: the invoiced quantity does not match the invoice document.', r.e, r.p));
  end loop;

  -- 9. Contract accounting clearing balances (cleared items - residual item = 0).
  if exists (select 1 from pg_temp.erp_chg c where c.code = 'DFKKOP' and c.op = 'update'
              and c.old->>'status' = 'Open' and c.new->>'status' = 'Cleared') then
    select coalesce(sum((c.new->>'betrw')::numeric), 0) into v_sum from pg_temp.erp_chg c
     where c.code = 'DFKKOP' and c.op = 'update' and c.old->>'status' = 'Open' and c.new->>'status' = 'Cleared';
    select v_sum - coalesce(sum((c.new->>'betrw')::numeric), 0) into v_sum from pg_temp.erp_chg c
     where c.code = 'DFKKOP' and c.op = 'insert' and c.new->>'status' = 'Open' and c.new->>'txt' like 'Residual item%';
    if abs(v_sum) > 0.009 then
      perform erp.fail(format('The FI-CA clearing is not balanced: difference %s.', to_char(v_sum, 'FM999G999G999G990D00')));
    end if;
  end if;

  -- 10. Billing: a billing document totals the billable items billed with it;
  --     items are unbilled only together with the reversal of their document.
  for r in select c.new from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'DFKKINVBILL' loop
    select count(*), coalesce(sum((c.new->>'bitamount')::numeric), 0) into v_n, v_amt from pg_temp.erp_chg c
     where c.code = 'DFKKBIX' and c.new->>'invdoc' = r.new->>'invdoc' and c.new->>'status' = 'Billed';
    if v_n = 0 or v_amt <> (r.new->>'amount')::numeric then
      perform erp.fail(format('Billing document %s does not match the amount of its billable items.', r.new->>'invdoc'));
    end if;
  end loop;
  for r in select c.old, c.new from pg_temp.erp_chg c where c.op = 'update' and c.code = 'DFKKBIX'
            and (c.old->>'status') is distinct from (c.new->>'status') loop
    if r.new->>'status' = 'Billed' and not exists (select 1 from pg_temp.erp_chg x where x.op = 'insert'
                                                     and x.code = 'DFKKINVBILL' and x.new->>'invdoc' = r.new->>'invdoc') then
      perform erp.fail(format('%s can only be billed with a new billing document.', erp.describe('DFKKBIX', r.new)));
    end if;
    if r.old->>'status' = 'Billed' and not exists (select 1 from erp.billing_documents b where b.workspace_id = p_ws
                                                     and b.invdoc = r.old->>'invdoc' and b.status = 'Reversed') then
      perform erp.fail(format('%s can only be unbilled by reversing billing document %s.', erp.describe('DFKKBIX', r.new), r.old->>'invdoc'));
    end if;
  end loop;
  for r in select c.new from pg_temp.erp_chg c where c.op = 'update' and c.code = 'DFKKINVBILL'
            and c.new->>'status' = 'Reversed' and c.old->>'status' <> 'Reversed' loop
    if exists (select 1 from erp.billable_items b where b.workspace_id = p_ws and b.invdoc = r.new->>'invdoc' and b.status = 'Billed') then
      perform erp.fail(format('Billing document %s still has billed items.', r.new->>'invdoc'));
    end if;
  end loop;

  -- 11. New scanned VIM documents start at the beginning of the workflow.
  for r in select c.new from pg_temp.erp_chg c where c.op = 'insert' and c.code = 'VIMDP' loop
    if r.new->>'proc_status' <> 'New' then
      perform erp.fail(format('%s must start with status New.', erp.describe('VIMDP', r.new)));
    end if;
  end loop;
end $$;

-- Applies a batch of changes atomically for one workspace.
create or replace function erp.commit(p_ws uuid, p_request_id uuid, p_ops jsonb, p_actor text)
returns jsonb language plpgsql set search_path = ''
as $$
declare
  v_kind text;
  v_prev jsonb;
  v_text text;
  v_numbers jsonb := '{}';
  t record;
  v_num text;
  v_ops jsonb;
  v_op jsonb;
  v_seq integer := 0;
  v_result jsonb;
begin
  if p_request_id is null then perform erp.fail('Invalid request.'); end if;
  -- One writer per workspace at a time; also serializes duplicate requests.
  select kind into v_kind from erp.workspaces where id = p_ws for update;
  if v_kind is distinct from 'session' then perform erp.fail('Workspace not found.'); end if;

  select c.result into v_prev from erp.commits c where c.workspace_id = p_ws and c.request_id = p_request_id;
  if found then
    return v_prev || jsonb_build_object('replayed', true);
  end if;

  if p_ops is null or jsonb_typeof(p_ops) <> 'array' or jsonb_array_length(p_ops) = 0 or jsonb_array_length(p_ops) > 5000 then
    perform erp.fail('Invalid request.');
  end if;

  -- Document numbers: the browser uses placeholders such as {#FI.1#}; the
  -- database assigns the real numbers from the workspace's number ranges.
  v_text := p_ops::text;
  for t in select distinct m[1] as tok, lower(m[2]) as name
             from regexp_matches(v_text, '(\{#([A-Z0-9]{1,12})\.[0-9]{1,6}#\})', 'g') as m loop
    v_num := erp.next_number(p_ws, t.name);
    v_text := replace(v_text, t.tok, v_num);
    v_numbers := v_numbers || jsonb_build_object(t.tok, v_num);
  end loop;
  v_ops := v_text::jsonb;

  create temp table if not exists erp_chg (seq integer, code text, op text, old jsonb, new jsonb) on commit drop;
  truncate pg_temp.erp_chg;

  for v_op in select value from jsonb_array_elements(v_ops) loop
    v_seq := v_seq + 1;
    perform erp.apply_op(p_ws, v_op, v_seq);
  end loop;

  perform erp.validate_batch(p_ws);
  set constraints all immediate;

  v_result := jsonb_build_object('numbers', v_numbers, 'committed_at', now(), 'changes', v_seq);
  insert into erp.commits (workspace_id, request_id, actor, ops, result)
  values (p_ws, p_request_id, left(coalesce(p_actor, 'unknown'), 80), v_ops, v_result);
  truncate pg_temp.erp_chg;
  return v_result;
end $$;

-- All data of a workspace in the module's table format.
create or replace function erp.export(p_ws uuid)
returns jsonb language plpgsql stable set search_path = ''
as $$
declare
  g erp.table_registry;
  v_tables jsonb := '{}';
  v_rows jsonb;
  v_expr text;
  v_lines jsonb;
begin
  for g in select * from erp.table_registry order by ord loop
    select string_agg(case c.kind
                        when 'text' then format('coalesce(t.%I, %L)', c.col, '')
                        when 'date' then format('coalesce(to_char(t.%I, %L), %L)', c.col, 'YYYY-MM-DD', '')
                        else format('coalesce(to_jsonb(t.%I), %L::jsonb)', c.col, '""')
                      end, ', ' order by c.ord)
      into v_expr from erp.table_columns c where c.code = g.code;
    execute format('select coalesce(jsonb_agg(jsonb_build_array(%s) order by t.seq), ''[]''::jsonb) from erp.%I t %s',
                   v_expr, g.relname, case when g.scope = 'workspace' then 'where t.workspace_id = $1' else '' end)
      into v_rows using p_ws;
    v_tables := v_tables || jsonb_build_object(g.code, jsonb_build_object(
      'd', g.description,
      'c', (select jsonb_agg(c.app_name order by c.ord) from erp.table_columns c where c.code = g.code),
      'l', (select jsonb_agg(c.label order by c.ord) from erp.table_columns c where c.code = g.code),
      'r', v_rows));
  end loop;

  select coalesce(jsonb_object_agg(doc_table, docs), '{}'::jsonb) into v_lines from (
    select doc_table, jsonb_object_agg(belnr, lines) as docs from (
      select doc_table, belnr,
             jsonb_agg(jsonb_build_object('BUZEI', buzei, 'BSCHL', bschl, 'KOART', koart, 'ACC', acc, 'AMT', amt,
                                          'MWSKZ', coalesce(mwskz, ''), 'ZUONR', coalesce(zuonr, ''), 'SGTXT', coalesce(sgtxt, ''),
                                          'KOSTL', coalesce(kostl, ''), 'UMSKZ', coalesce(umskz, ''), 'GSBER', coalesce(gsber, ''))
                       order by buzei) as lines
        from erp.document_lines where workspace_id = p_ws group by doc_table, belnr) x
     group by doc_table) y;

  return jsonb_build_object('tables', v_tables, 'lines', v_lines, 'server_date', to_char(current_date, 'YYYY-MM-DD'));
end $$;

-- -----------------------------------------------------------------------------
-- Baseline import (repeatable, idempotent, atomic)
-- -----------------------------------------------------------------------------
create or replace function erp.import_baseline(p_payload jsonb, p_meta jsonb)
returns jsonb language plpgsql set search_path = ''
as $$
declare
  v_ws uuid;
  v_import bigint;
  g erp.table_registry;
  v_rows jsonb;
  v_cols text; v_sel text; v_upd text; v_cmp_t text; v_cmp_x text; v_conflict text;
  v_ins bigint; v_upd_n bigint;
  v_counts jsonb := '{}';
  v_fy integer;
begin
  if p_meta->>'file_sha256' !~ '^[0-9a-f]{64}$' then perform erp.fail('Invalid import metadata.'); end if;
  set constraints all deferred;

  v_ws := erp.baseline_id();
  if v_ws is null then
    insert into erp.workspaces (kind) values ('baseline') returning id into v_ws;
  end if;

  insert into erp.import_runs (file_name, file_sha256, mapping_version, status)
  values (left(coalesce(p_meta->>'file_name', 'unknown'), 200), p_meta->>'file_sha256',
          coalesce(p_meta->>'mapping_version', 'unknown'), 'applied')
  returning id into v_import;

  for g in select * from erp.table_registry order by ord loop
    v_rows := p_payload->'tables'->g.code;
    if v_rows is null then continue; end if;
    if jsonb_typeof(v_rows) <> 'array' then perform erp.fail(format('Invalid rows for %s.', g.code)); end if;

    select string_agg(format('%I', c), ', ' order by o),
           string_agg(format('r.%I', c), ', ' order by o),
           string_agg(format('%I = excluded.%I', c, c), ', ' order by o) filter (where c <> all (g.key_cols)),
           string_agg(format('t.%I', c), ', ' order by o) filter (where c <> all (g.key_cols)),
           string_agg(format('excluded.%I', c), ', ' order by o) filter (where c <> all (g.key_cols))
      into v_cols, v_sel, v_upd, v_cmp_t, v_cmp_x
      from unnest(erp.cols(g.code)) with ordinality as x(c, o);

    if g.code = 'T001' then
      -- Keep names a teacher has configured.
      v_upd := replace(v_upd, 'butxt = excluded.butxt', 'butxt = case when t.name_configured then t.butxt else excluded.butxt end');
      v_cmp_t := replace(v_cmp_t, 't.butxt', 'case when t.name_configured then null else t.butxt end');
      v_cmp_x := replace(v_cmp_x, 'excluded.butxt', 'case when t.name_configured then null else excluded.butxt end');
    end if;

    v_conflict := (select string_agg(format('%I', k), ', ') from unnest(g.key_cols) k);
    if g.scope = 'workspace' then
      execute format($q$
        with src as (
          select r.*, e.ord from jsonb_array_elements($1) with ordinality as e(value, ord),
                 lateral jsonb_populate_record(null::erp.%1$I, e.value) r),
        up as (
          insert into erp.%1$I as t (workspace_id, %2$s)
          select $2, %3$s from src r order by r.ord
          on conflict (workspace_id, %4$s) do update set %5$s
           where (%6$s) is distinct from (%7$s)
          returning (xmax = 0) as inserted)
        select count(*) filter (where inserted), count(*) filter (where not inserted) from up$q$,
        g.relname, v_cols, v_sel, v_conflict, v_upd, v_cmp_t, v_cmp_x)
        into v_ins, v_upd_n using v_rows, v_ws;
    else
      execute format($q$
        with src as (
          select r.*, e.ord from jsonb_array_elements($1) with ordinality as e(value, ord),
                 lateral jsonb_populate_record(null::erp.%1$I, e.value) r),
        up as (
          insert into erp.%1$I as t (%2$s)
          select %3$s from src r order by r.ord
          on conflict (%4$s) do update set %5$s
           where (%6$s) is distinct from (%7$s)
          returning (xmax = 0) as inserted)
        select count(*) filter (where inserted), count(*) filter (where not inserted) from up$q$,
        g.relname, v_cols, v_sel, v_conflict, v_upd, v_cmp_t, v_cmp_x)
        into v_ins, v_upd_n using v_rows;
    end if;
    v_counts := v_counts || jsonb_build_object(g.code, jsonb_build_object(
      'rows', jsonb_array_length(v_rows), 'inserted', v_ins, 'updated', v_upd_n,
      'unchanged', jsonb_array_length(v_rows) - v_ins - v_upd_n));
  end loop;

  insert into erp.import_normalizations (import_id, code, row_key, col, original, normalized, rule)
  select v_import, n->>'code', n->>'row_key', n->>'col', n->>'original', n->>'normalized', n->>'rule'
    from jsonb_array_elements(coalesce(p_payload->'normalizations', '[]'::jsonb)) n
  on conflict do nothing;

  -- Open posting periods for the fiscal years in the data, the current and the next year.
  for v_fy in
    select distinct fy from (
      select erp.fiscal_year(budat) as fy from erp.vendor_items where workspace_id = v_ws
      union select erp.fiscal_year(current_date) union select erp.fiscal_year(current_date) + 1) y
  loop
    insert into erp.posting_periods (bukrs, fiscal_year, from_period, to_period)
    select bukrs, v_fy, 1, 12 from erp.company_codes
    on conflict (bukrs, fiscal_year) do nothing;
  end loop;

  set constraints all immediate;
  update erp.import_runs set counts = v_counts, finished_at = now() where id = v_import;
  return jsonb_build_object('import_id', v_import, 'counts', v_counts);
end $$;

